// Renders the Topic Card catalog (src/data) as Dart source for the Flutter app.
// ADR 0006: the mobile catalog is generated Dart, not a JSON asset, so Shorebird patches can update it.
import type { Subfield, Subject, TopicCard } from '@/types/domain';

const dartString = (value: string) =>
  `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\r?\n/g, '\\n')}'`;

const dartList = (values: readonly string[]) => `[${values.map(dartString).join(', ')}]`;

export function renderDartCatalog(subjects: Subject[], subfields: Subfield[], cards: TopicCard[]): string {
  const lines: string[] = [
    '// GENERATED by tests/unit/mobile-dart-catalog.test.ts from src/data. Do not edit by hand.',
    '// Regenerate: UPDATE_DART_CATALOG=1 npx vitest run tests/unit/mobile-dart-catalog.test.ts',
    "import 'catalog.dart';",
    '',
    'const List<DiscoverySubject> discoverySubjects = [',
    ...subjects.map(
      (s) => `  DiscoverySubject(id: ${dartString(s.id)}, nameTh: ${dartString(s.nameTh)}, description: ${dartString(s.description)}),`,
    ),
    '];',
    '',
    'const List<DiscoverySubfield> discoverySubfields = [',
    ...subfields.map(
      (f) =>
        `  DiscoverySubfield(id: ${dartString(f.id)}, subjectId: ${dartString(f.subjectId)}, nameTh: ${dartString(f.nameTh)}, description: ${dartString(f.description)}),`,
    ),
    '];',
    '',
    'const List<DiscoveryCard> discoveryCatalogCards = [',
  ];
  for (const c of cards) {
    lines.push(
      '  DiscoveryCard(',
      `    id: ${dartString(c.id)},`,
      `    subjectId: ${dartString(c.subjectId)},`,
      `    subfieldId: ${dartString(c.subfieldId)},`,
      `    title: ${dartString(c.title)},`,
      `    phenomenon: ${dartString(c.phenomenon)},`,
      `    curiosityHook: ${dartString(c.curiosityHook)},`,
      `    gradeLevels: ${dartList(c.targetGradeLevels)},`,
      `    difficulty: ${dartString(c.difficulty)},`,
      `    estimatedWeeks: ${c.estimatedWeeks},`,
      `    estimatedBudgetBaht: ${c.estimatedBudgetBaht},`,
      `    requiredEquipment: ${dartList(c.requiredEquipment)},`,
      `    minTeamSize: ${c.minTeamSize},`,
      `    maxTeamSize: ${c.maxTeamSize},`,
      `    requiredSkills: ${dartList(c.requiredSkills)},`,
      '  ),',
    );
  }
  lines.push('];', '');
  return lines.join('\n');
}
